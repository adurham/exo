#!/usr/bin/env python3
"""Focused xctrace Metal aggregation: GPU-busy time + command-buffer/kernel counts.

NOTE (XXE): input XML is locally generated by `xctrace export` from our own
recorded trace on a trusted node -- stdlib ElementTree is safe here.
"""
import json
import xml.etree.ElementTree as ET

DIR = "/tmp/p20_pmp_A/raw/C"


def cols_of(root):
    s = root.find(".//schema")
    return [c.findtext("mnemonic") for c in s.findall("col")]


def rows_of(path):
    r = ET.parse(path).getroot()
    return cols_of(r), r.findall(".//row")


def num(ch):
    txt = ch.text if ch.text is not None else ch.get("fmt")
    try:
        return float(str(txt).replace(",", ""))
    except Exception:
        return None


out = {}

# --- GPU Execution intervals (top-level, Active) -> GPU busy time ---
cols, rows = rows_of(f"{DIR}/xctrace_metal-gpu-intervals.xml")
i_start, i_dur, i_lbl, i_state, i_depth = (cols.index("start"), cols.index("duration"),
                                           cols.index("event-label"), cols.index("state"),
                                           cols.index("event-depth"))
busy_ns = 0.0
by_cat = {}
t_min, t_max = None, None
n_active = 0
for r in rows:
    ch = list(r)
    d = num(ch[i_dur])
    s = num(ch[i_start])
    if s is not None:
        t_min = s if t_min is None else min(t_min, s)
        t_max = s if t_max is None else max(t_max, s)
    lbl = ch[i_lbl].get("fmt") or ch[i_lbl].text or ""
    st = (ch[i_state].get("fmt") if ch[i_state].get("fmt") is not None else ch[i_state].text)
    if d is not None:
        cat = "GPU Execution" if lbl.startswith("GPU Execution") else (lbl[:24] or "(noname)")
        by_cat[cat] = by_cat.get(cat, 0.0) + d
        if lbl.startswith("GPU Execution") and str(st) == "Active":
            busy_ns += d
            n_active += 1
out["metal-gpu-intervals"] = {
    "n_rows": len(rows),
    "gpu_exec_intervals_active": n_active,
    "gpu_busy_ms": round(busy_ns / 1e6, 2),
    "span_s": round((t_max - t_min) / 1e9, 3) if (t_min is not None and t_max is not None) else None,
    "by_category_ms": {k: round(v / 1e6, 2) for k, v in sorted(by_cat.items(), key=lambda kv: -kv[1])[:10]},
}

# --- command buffers completed ---
cols, rows = rows_of(f"{DIR}/xctrace_metal-command-buffer-completed.xml")
out["metal-command-buffer-completed"] = {"n_rows": len(rows)}

cols, rows = rows_of(f"{DIR}/xctrace_metal-application-command-buffer-submissions.xml")
out["metal-application-command-buffer-submissions"] = {"n_rows": len(rows)}

cols, rows = rows_of(f"{DIR}/xctrace_metal-application-intervals.xml")
names = {}
for r in rows:
    ch = list(r)
    lbl = ch[cols.index("event-label")].get("fmt") or ""
    for pre in ("Command Buffer", "Compute Command", "Blit", "Encoding", "GPU"):
        if lbl.startswith(pre):
            names[pre] = names.get(pre, 0) + 1
            break
    else:
        names["other"] = names.get("other", 0) + 1
out["metal-application-intervals"] = {"n_rows": len(rows), "label_prefix_counts": names}

cols, rows = rows_of(f"{DIR}/xctrace_metal-gpu-execution-points.xml")
out["metal-gpu-execution-points"] = {"n_rows": len(rows)}

json.dump(out, open(f"{DIR}/xctrace_agg.json", "w"), indent=1)
print(json.dumps(out, indent=1))
